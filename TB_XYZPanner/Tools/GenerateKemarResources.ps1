[CmdletBinding()]
param([switch]$Download)

$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$resourceDirectory = Join-Path $projectRoot 'Source\Resources\KemarHrtf'
$archivePath = Join-Path $resourceDirectory 'kemar_hrir.zip'
$sourceUrl = 'https://sound.media.mit.edu/resources/KEMAR/compact.zip'
$expectedHash = '0BCD69F8E8760CF8EACFF4A89594CECA7D44FB94F28ECF0BF19970003BBFB3E0'
$expectedBytes = 231461

if ($Download)
{
    [byte[]]$archiveBytes = (Invoke-WebRequest -Uri $sourceUrl -UseBasicParsing).Content
}
else
{
    [byte[]]$archiveBytes = [IO.File]::ReadAllBytes($archivePath)
}

$sha256 = [Security.Cryptography.SHA256]::Create()
try
{
    $actualHash = [BitConverter]::ToString($sha256.ComputeHash($archiveBytes)).Replace('-', '')
}
finally
{
    $sha256.Dispose()
}

if ($archiveBytes.Length -ne $expectedBytes -or $actualHash -ne $expectedHash)
{
    throw "MIT compact archive does not match the reviewed source: $actualHash ($($archiveBytes.Length) bytes)."
}

# Validate every measurement consumed by the renderer before changing generated files.
Add-Type -AssemblyName System.IO.Compression
$memory = New-Object IO.MemoryStream(,$archiveBytes)
$archive = New-Object IO.Compression.ZipArchive($memory)
$validatedCount = 0
try
{
    # Directions around the full circle on each elevation row, -40 to +90 degrees.
    # The archive holds the right-hand half of each row: 0 up to at most 180 degrees.
    $fullCircleCounts = 56, 60, 72, 72, 72, 72, 72, 60, 56, 45, 36, 24, 12, 1
    for ($row = 0; $row -lt $fullCircleCounts.Count; ++$row)
    {
        $elevation = -40 + 10 * $row
        $step = 360.0 / $fullCircleCounts[$row]
        $intervals = [int][Math]::Floor(180.0 / $step + 0.001)
        for ($index = 0; $index -le $intervals; ++$index)
        {
            $azimuth = [int][Math]::Round($index * $step)
            $entryName = 'elev{0}/H{0}e{1:000}a.wav' -f $elevation, $azimuth
            $entry = $archive.GetEntry($entryName)
            if ($null -eq $entry) { throw "Missing HRIR: $entryName" }

            $input = $entry.Open()
            $wavStream = New-Object IO.MemoryStream
            try
            {
                $input.CopyTo($wavStream)
                $wav = $wavStream.ToArray()
            }
            finally
            {
                $input.Dispose()
                $wavStream.Dispose()
            }

            # The pinned official compact ZIP stores canonical 44-byte PCM WAV headers.
            if ($wav.Length -ne 556 -or
                [Text.Encoding]::ASCII.GetString($wav, 0, 4) -ne 'RIFF' -or
                [Text.Encoding]::ASCII.GetString($wav, 8, 4) -ne 'WAVE' -or
                [BitConverter]::ToUInt16($wav, 20) -ne 1 -or
                [BitConverter]::ToUInt16($wav, 22) -ne 2 -or
                [BitConverter]::ToUInt32($wav, 24) -ne 44100 -or
                [BitConverter]::ToUInt16($wav, 34) -ne 16 -or
                [Text.Encoding]::ASCII.GetString($wav, 36, 4) -ne 'data' -or
                [BitConverter]::ToUInt32($wav, 40) -ne 512)
            {
                throw "Unexpected compact HRIR format: $entryName"
            }
            ++$validatedCount
        }
    }
}
finally
{
    $archive.Dispose()
    $memory.Dispose()
}

$newline = "`n"
$builder = New-Object Text.StringBuilder
[void]$builder.Append('// Generated by Tools/GenerateKemarResources.ps1. Do not edit by hand.').Append($newline)
[void]$builder.Append('// MIT Media Laboratory, Bill Gardner and Keith Martin (1994).').Append($newline)
[void]$builder.Append('// Source: ').Append($sourceUrl).Append($newline)
[void]$builder.Append('// SHA-256: ').Append($expectedHash).Append($newline).Append($newline)
[void]$builder.Append('#include "HrtfResources.h"').Append($newline).Append($newline)
[void]$builder.Append('static constexpr unsigned char kemar_hrir_zip_local[] =').Append($newline).Append('{').Append($newline)
for ($offset = 0; $offset -lt $archiveBytes.Length; $offset += 32)
{
    $end = [Math]::Min($offset + 31, $archiveBytes.Length - 1)
    [void]$builder.Append('    ').Append(($archiveBytes[$offset..$end] -join ','))
    if ($end + 1 -lt $archiveBytes.Length) { [void]$builder.Append(',') }
    [void]$builder.Append($newline)
}
[void]$builder.Append('};').Append($newline).Append($newline)
[void]$builder.Append('const char* kemar_hrir_zip = reinterpret_cast<const char*> (kemar_hrir_zip_local);').Append($newline)

$header = @(
    '// Generated by Tools/GenerateKemarResources.ps1. Do not edit by hand.'
    '#pragma once'
    ''
    'extern const char* kemar_hrir_zip;'
    ('const unsigned int kemar_hrir_zipSize = {0};' -f $archiveBytes.Length)
) -join $newline
$utf8 = New-Object Text.UTF8Encoding($false)
if ($Download) { [IO.File]::WriteAllBytes($archivePath, $archiveBytes) }
[IO.File]::WriteAllText((Join-Path $projectRoot 'Source\HrtfResources.cpp'), $builder.ToString(), $utf8)
[IO.File]::WriteAllText((Join-Path $projectRoot 'Source\HrtfResources.h'), $header + $newline, $utf8)

Write-Output "Generated kemar_hrir_zip: $($archiveBytes.Length) bytes, SHA-256 $actualHash"
Write-Output "Validated $validatedCount stereo HRIRs across fourteen elevation rows, -40 to +90 degrees."
